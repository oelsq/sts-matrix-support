"""Narrow public-rights explanations, conditional on the actual source clauses.

These are not generated LLM replies. Do not activate a rule merely because the
file exists: the scoped search result must contain the supporting wording.
"""
import re
from agents import render
from response_guidance import is_document_request
from retrieval_intents import loan_status_notification


def _find(evidence, document, article, *conditions):
    for passage in evidence:
        text = ' '.join(passage['text'].split())
        if (passage['document_id'] == document
                and str(passage.get('section', '')).startswith('Статья ' + article + '.')
                and all(term in text for term in conditions)):
            return passage
    return None


def checked_public_rights_answer(domain, question, evidence):
    current = question.split('\nПредыдущий вопрос:')[0]
    q = question.casefold()
    draft = is_document_request(current)
    # Do not answer a calculation, statutory deadline, or court filing request
    # with a generic pre-litigation checklist. Those need different evidence.
    if re.search(r'срок|скольк.*(?:дн|день|компенсац)|рассчит|исков|\bиск\b|госпошлин|компенсаци', current, re.I):
        return None
    if draft and re.search(r'суд|прокурат|полици', current, re.I):
        return None
    if loan_status_notification(question) and not draft:
        warning = next((p for p in evidence if p['document_id']=='nb-phishing-loan'
                        and 'не переходить по ссылкам' in ' '.join(p['text'].split())
                        and 'Государственного кредитного бюро' in ' '.join(p['text'].split())), None)
        introduction = next((p for p in evidence if p['document_id']=='nb-phishing-loan'
                             and 'статус вашего займа был обновлен' in ' '.join(p['text'].split())
                             and re.search(r'поддельн\s*ый сайт', ' '.join(p['text'].split()))), None)
        if warning and introduction:
            sources = [introduction]
            ref = '[S1]'
            if warning['id'] != introduction['id']:
                sources.append(warning)
                ref = '[S2]'
            return render(domain,
                '**Не переходите по ссылке из такого сообщения.** Нацбанк предупреждает о рассылке '
                'сообщений «статус вашего займа был обновлен» со ссылкой на поддельный сайт. [S1]\n\n'
                '**Как проверить ситуацию**\n'
                '1. Самостоятельно откройте официальный сайт Государственного кредитного бюро '
                'или портал электронного правительства и проверьте свою кредитную историю — '
                'именно эти источники рекомендует Нацбанк. '+ref+'\n'
                '2. Не вводите в форме из сообщения данные удостоверения, реквизиты карты или другие '
                'конфиденциальные сведения: поддельные сайты запрашивают их для получения доступа к данным. [S1]\n'
                '3. Сохраните сообщение. Если обнаружили незнакомый договор, выделите эту запись '
                'в официальном отчёте — затем можно подготовить обращение для проверки.\n\n'
                'Вы только получили сообщение или уже переходили по ссылке и вводили данные? '
                'Само сообщение и личные реквизиты в общий чат пересылать не нужно.', question, sources)
    if re.search(r'кредитн.*(?:истори|отч[её]т)|\bбки\b', q):
        dispute = re.search(r'ошиб|неверн|недостовер|закрыт|погас|чуж|исправ', q)
        if dispute:
            rights = _find(evidence, 'credit-history', '22',
                           'заявлять несогласие с информацией',
                           'требованием об исправлении недостоверной информации')
            procedure = _find(evidence, 'credit-history', '31',
                              'указание на оспариваемую информацию',
                              'требование о предоставлении достоверной информации',
                              'Заявление подписывается заявителем')
            if not rights or not procedure:
                return None
            if draft:
                answer = (
                    '**Черновик заявления об исправлении кредитной истории**\n\n'
                    'Кому: [кредитное бюро / поставщик информации]\n'
                    'От: [ФИО заявителя]\nАдрес: [адрес]\n'
                    'Документ, удостоверяющий личность: [данные для подачи адресату]\n\n'
                    'В кредитном отчёте от [дата] указаны сведения: [запись, кредитор, договор]. '
                    'Я не согласен(на) с этой информацией, поскольку [описание ошибки]. '
                    'Моя позиция подтверждается [документы о погашении / другое подтверждение].\n\n'
                    'Прошу проверить указанную запись, исправить недостоверную информацию при подтверждении ошибки '
                    'и предоставить достоверную информацию. Если основания для исправления отсутствуют, '
                    'прошу направить письменный ответ с указанием источника оспариваемых сведений.\n\n'
                    'Приложения: [копия спорной части отчёта и подтверждающих документов].\n'
                    'Дата: [дата]\nПодпись: [подпись]\n\n'
                    'Это редактируемый образец для физического лица: содержание заявления и его подписание '
                    'предусмотрены статьёй 31. Заполните личные данные у себя для подачи адресату, '
                    'а не в общем чате. [S2]'
                )
            else:
                answer = (
                    'Вы можете оспорить неверную запись: статья 22 позволяет заявить несогласие с информацией '
                    'в кредитном отчёте и обратиться к поставщику сведений с требованием об исправлении. [S1]\n\n'
                    '**Что сделать сейчас**\n'
                    '1. Сохраните спорный отчёт и отметьте конкретную запись: кредитора, договор и неверные сведения.\n'
                    '2. Подайте подписанное заявление в кредитное бюро или поставщику информации. '
                    'Укажите, что оспариваете и какую информацию считаете достоверной; '
                    'можно приложить подтверждающие документы. [S2]\n'
                    '3. Сохраните заявление и подтверждение его получения.\n\n'
                    'Это проверка ошибки, а не способ стереть достоверную просрочку. '
                    'Статья 31 предусматривает и письменный отказ с указанием источников, '
                    'если оспариваемая информация соответствует сведениям бюро и поставщика. [S3]\n\n'
                    'Какая именно запись неверна: кредит не закрыт после погашения, чужой заём или другая ошибка?'
                )
            # The rejection condition is part of the same statutory procedure;
            # do not turn a fragmented source into a promise of deletion.
            refusal = _find(evidence, 'credit-history', '31',
                            'направляют заявителю письменный отказ',
                            'соответствует сведениям кредитного бюро')
            if not refusal:
                return None
            sources = [rights, procedure]
            if refusal['id'] == procedure['id']:
                answer = answer.replace('[S3]', '[S2]')
            else:
                sources.append(refusal)
            return render(domain, answer, question, sources)
        if not draft and re.search(r'получ|посмотр|провер|ознаком|заказ', current, re.I):
            rights = _find(evidence, 'credit-history', '22', 'кредитный отчет о себе',
                           'с момента поступления информации о нем в кредитное бюро')
            if rights:
                return render(domain,
                    'Вы вправе получить кредитный отчёт о себе после поступления информации о вас в кредитное бюро. '
                    'При рассмотрении заявки на кредит можно также требовать ознакомления с отчётом либо выдачи его '
                    'копии в соответствии с внутренними правилами получателя отчёта. [S1]\n\n'
                    'Начните с запроса собственного отчёта через официальный канал бюро. '
                    'Сверьте кредитора, сумму и состояние обязательств; при ошибке выделите спорную запись '
                    'и сохраните подтверждающие документы. Не отправляйте весь отчёт с личными данными в общий чат.\n\n'
                    'Вам нужно получить отчёт впервые или разобраться с конкретной записью?', question, [rights])
    if draft:
        return None
    if 'профсоюз' in q and re.search(r'выйти|вступ|застав|дискриминац|огранич|уволь', current, re.I):
        rule = _find(evidence, 'trade-unions', '7', 'Запрещаются дискриминация при приеме на работу',
                     'Запрещается воздействие на лиц угрозой')
        if rule:
            return render(domain,
                'Статья 7 запрещает дискриминацию при приёме, продвижении и увольнение по инициативе работодателя '
                'из-за принадлежности к профсоюзу, вступления или выхода из него. '
                'Также запрещено угрозами или другими неправомерными действиями принуждать к невступлению '
                'либо переходу из одного профсоюза в другой. [S1]\n\n'
                '**Что можно сделать**\n'
                '- Сохраните письменное требование и переписку; запишите дату, участников и точные слова.\n'
                '- Попросите письменно объяснить основание требования и связанных с ним кадровых решений.\n'
                '- Если уже издан приказ или изменены условия работы, сохраните его копию: '
                'это позволит отдельно разобраться в конкретном решении.\n\n'
                'Пока это устное требование или уже есть письменное решение работодателя?', question, [rule])
    if ((re.search(r'долев|дольщик', q) or re.search(r'новостройк', q) and re.search(r'куп|покуп|застрой', q))
            and re.search(r'документ|запрос|провер|перед.*(?:покуп|оплат)|способ.*привлек', current, re.I)):
        methods = _find(evidence, 'shared-construction', '7', 'получение гарантии Единого оператора',
                        'участие в проекте банка второго уровня',
                        'привлечение денег дольщиков после возведения каркаса')
        info = _find(evidence, 'shared-construction', '22', 'о наименовании и юридическом адресе',
                     'о наличии договора о предоставлении гарантии',
                     'о наличии разрешения местного исполнительного органа')
        if methods and info:
            return render(domain,
                'Перед передачей денег запросите сведения об уполномоченной компании '
                'и законном способе привлечения денег дольщиков. Статья 7 предусматривает '
                'гарантию Единого оператора, участие банка в проекте либо привлечение денег после '
                'возведения каркаса; это разные способы, а не требование получить все документы сразу. [S1]\n\n'
                '**Что проверить у компании**\n'
                '- Наименование, юридический адрес и сведения о государственной регистрации.\n'
                '- При способе с гарантией — наличие договора гарантии и его основные условия.\n'
                '- При способе с банком или готовым каркасом — разрешение местного исполнительного органа '
                'на привлечение денег дольщиков. [S2]\n\n'
                'Сверьте реквизиты компании в документах и предлагаемом договоре. '
                'Одна рекламная презентация не заменяет этих проверок. '
                'Конкретный договор и подлинность документов по сообщению в чате подтвердить нельзя.\n\n'
                'Какой способ привлечения денег указывает компания и какой договор предлагает подписать?',
                question, [methods, info])
    if (re.search(r'дтп|автострах|осаго|огпо.*авто', q)
            and re.search(r'удерж|выч[её]л|расход.*оцен|оцен.*расход', current, re.I)):
        rule = _find(evidence, 'auto-insurance', '22',
                     'Страховщик не вправе удерживать со страховой выплаты',
                     'собственные расходы, связанные с определением размера вреда')
        if rule:
            return render(domain,
                'Если речь о собственных расходах страховщика на определение размера вреда, '
                'удерживать их из выплаты выгодоприобретателю нельзя: это прямо предусмотрено '
                'статьёй 22 закона об обязательном страховании ответственности владельцев транспорта. [S1]\n\n'
                '**Как разобраться с удержанием**\n'
                '1. Запросите письменный расчёт выплаты с отдельным указанием удержаний.\n'
                '2. Если удержаны именно эти расходы, укажите на запрет и попросите пересмотреть расчёт.\n'
                '3. Сохраните расчёт, заявление и ответ страховщика.\n\n'
                'Это правило о расходах самого страховщика, а не обещание оплаты любых услуг '
                'вашего оценщика. Для такого требования нужны отдельные основания. '
                'Что именно указано в расчёте как удержание?', question, [rule])
    return None
