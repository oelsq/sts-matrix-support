"""Product help from implemented features, outside legal-source inference."""
import re


# Match the whole request, including combinations without punctuation. A
# substring such as "какие команды" must never swallow an actual legal case.
_PARTS = (
    r"(?:что|чем) (?:ты |вы )?(?:умеешь|умеете|можешь|можете)(?: (?:делать|помочь|помочь мне))?",
    r"чем (?:ты |вы )?(?:поможешь|поможете)(?: мне)?",
    r"что умеет (?:юрагент|финагент|этот бот)",
    r"(?:какие|что за) (?:(?:у тебя|у вас) )?(?:есть )?(?:команды|функции|возможности)(?: (?:у тебя|у вас))?(?: есть| доступны)?",
    r"(?:список|перечень) (?:(?:твоих|ваших|доступных) )?(?:команд|функций|возможностей)",
    r"как (?:тобой|вами|ботом|этим ботом|юрагентом|финагентом) пользоваться",
    r"как пользоваться (?:тобой|вами|ботом|этим ботом|юрагентом|финагентом)",
    r"как (?:с тобой|с вами|с ботом) (?:работать|общаться)",
    r"кто (?:ты|вы)(?: такой| такая)?",
    r"что ты за бот",
    r"расскажи(?:те)? (?:мне )?о себе",
    r"какие команды (?:есть )?для (?:выбора|смены) сотрудника",
    r"как (?:выбрать|сменить|поменять) (?:другого )?сотрудника(?: по номеру)?",
    r"как (?:перейти|переключиться|перевестись) к другому сотруднику",
    r"как связаться с (?:сотрудником|человеком|юрдепом|финдепом)",
    r"помощь|справка|команды",
    r"what can you do|how can you help(?: me)?|who are you",
    r"what commands (?:do you (?:have|support)|are available)",
    r"(?:show|list) (?:your )?commands|how (?:do i use|to use) (?:you|this bot)",
)
_ATOM = "(?:" + "|".join(_PARTS) + ")"
_PREFIX = r"(?:(?:привет|здравствуйте|добрый день|слушай|пожалуйста|а|и|ну|еще|можешь|можете|расскажи|расскажите|покажи|покажите|подскажи|подскажите|скажи|скажите|объясни|объясните|обьясни|мне) )*"
_REQUEST = re.compile(_PREFIX + _ATOM + r"(?: (?:и |а |а еще |также )?" + _ATOM + r")*(?: пожалуйста)?")


def is_help_request(text):
    if not isinstance(text, str) or len(text) > 400:
        return False
    if text.strip().casefold() == "!помощь":
        return True
    text = " ".join(re.sub(r"[?!.,;:…]+", " ", text.casefold().replace("ё", "е")).split())
    return bool(_REQUEST.fullmatch(text))


def help_reply(text, domain=None):
    if not is_help_request(text):
        return None
    role, description, example = {
        "legal": (
            "ЮрАгент",
            "Помогу разобраться в юридической ситуации по доступным материалам Казахстана, "
            "объяснить норму простыми словами и подготовить черновик заявления или требования.",
            "Начальник не отдаёт деньги за работу",
        ),
        "finance": (
            "ФинАгент",
            "Помогу разобраться в кредитах, комиссиях и личных финансах по доступным материалам, "
            "проверить расчёт по вашим данным и подготовить обращение в банк.",
            "Что такое ГЭСВ и чем она отличается от ставки по кредиту?",
        ),
    }.get(domain, (
        "ИИ-помощник",
        "Помогу с юридическими и финансовыми вопросами по доступным материалам Казахстана: "
        "объяснить условия, разобрать ситуацию и подготовить черновик обращения.",
        "Начальник не отдаёт деньги за работу",
    ))
    return (
        f"**{role} — возможности и команды**\n\n{description}\n\n"
        "**Как пользоваться**\n\n"
        f"Задайте вопрос обычными словами, например: «{example}». "
        "Для продолжения пишите в этом же чате.\n\n"
        "**Команды**\n\n"
        "- `!помощь` — эта справка.\n"
        "- `!база` / `!темы` — темы доступной базы знаний.\n"
        "- `!новый` — начать новую тему; история комнаты сохраняется.\n"
        "- `!расчёт` — шаблон данных для расчёта переплаты по графику платежей.\n"
        "- `!сотрудники` — список сотрудников и команды выбора.\n"
        "- `!человек` — обратиться к сотруднику текущего департамента.\n"
        "- `!юрдеп` / `!финдеп` — выбрать департамент.\n"
        "- `!юрдеп2` / `!финдеп3` — выбрать конкретного сотрудника по номеру из списка.\n"
        "- `!другой` — перейти к следующему сотруднику; команду пишите в чате ИИ.\n"
        "- `!оценка полезно`, `!оценка неполно`, `!оценка ошибка`, "
        "`!оценка не помогло` — оценить свой последний ответ."
    )
