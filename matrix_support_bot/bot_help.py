        "- `!помощь` — эта справка.\n"
        "- `!база` / `!темы` — темы доступной базы знаний.\n"
        "- `!лично` — приглашение в личные зашифрованные комнаты, если включён защищённый режим.\n- `!новый` — начать новую тему; история комнаты сохраняется.\n"
        "- `!расчёт` — шаблон данных для расчёта переплаты по графику платежей.\n"
        "- `!сотрудники` — список сотрудников и команды выбора.\n"
        "- `!человек` — обратиться к сотруднику текущего департамента.\n"
        "- `!юрдеп` / `!финдеп` — выбрать департамент.\n"
        "- `!юрдеп2` / `!финдеп3` — выбрать конкретного сотрудника по номеру из списка.\n"
        "- `!другой` — перейти к следующему сотруднику; команду пишите в чате ИИ.\n"
        "- `!оценка полезно`, `!оценка неполно`, `!оценка ошибка`, "
