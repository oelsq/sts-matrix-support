def is_rental_refund_draft(question):
    from response_guidance import is_document_request
    current=question.split("\nПредыдущий вопрос:")[0]
    return bool(is_document_request(question) and re.search(r"аренд|квартир|найм", question, re.I)
                and re.search(r"залог|депозит|обеспеч|возврат|вернут", question, re.I)
                and not re.search(r"суд|исков|иск\b|прокурат|полици", current, re.I))


